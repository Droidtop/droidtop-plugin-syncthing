#!/usr/bin/env bash
# Builds droidtop.syncthing's payload into build/, in the shape PluginBundleInstaller.install() expects (droidtop
# docs/SPEC.md 12a): classes.jar (the Kotlin plugin, dexed) and lib/<abi>/libsyncthing.so for arm64-v8a and x86_64
# (upstream Syncthing as a Go c-shared library), with manifest.json listing each file's SHA-256. Unsigned: sign.sh is
# the only script that touches the key, and CI runs it in a job of its own.
#
# Upstream Syncthing is checked out at the tag and commit syncthing.pin names and is not changed: this repository's
# go/droidtopsyncthing package is copied into that tree as cmd/droidtopsyncthing and built there, so it compiles
# against exactly upstream's go.mod and go.sum.
#
# Prerequisites (droidtop-platforms' plugin bundle workflow provides them; prepare.sh installs Go):
#   - kotlinc and d8 on PATH, PLUGIN_HOST_CLASSPATH (droidtop's :plugin-host classes) and ANDROID_JAR
#   - go on PATH, at syncthing.pin's GO_VERSION
#   - the Android NDK: ANDROID_SDK_ROOT with NDK_VERSION (the workflow's own NDK), else ANDROID_NDK_HOME
#   - git, python3, zip, sha256sum
set -euo pipefail
cd "$(dirname "$0")"
# shellcheck source=syncthing.pin
. ./syncthing.pin

: "${PLUGIN_HOST_CLASSPATH:?set to a jar/dir containing dev.droidtop.pluginhost.* compiled classes}"
: "${ANDROID_JAR:?set ANDROID_JAR to android.jar for the target compileSdk}"
# The runner image's own ANDROID_NDK_HOME names an NDK the workflow removed to free space, so the workflow's NDK first.
if [ -n "${ANDROID_SDK_ROOT:-}" ] && [ -n "${NDK_VERSION:-}" ] && [ -d "$ANDROID_SDK_ROOT/ndk/$NDK_VERSION" ]; then
  NDK="$ANDROID_SDK_ROOT/ndk/$NDK_VERSION"
else
  NDK="${ANDROID_NDK_HOME:?set ANDROID_SDK_ROOT with NDK_VERSION, or ANDROID_NDK_HOME}"
fi
TOOLCHAIN="$NDK/toolchains/llvm/prebuilt/linux-x86_64/bin"
test -d "$TOOLCHAIN" || { echo "no NDK toolchain at $TOOLCHAIN" >&2; exit 1; }
# Native libraries load in droidtop's plugin sandbox from Android 9 (docs/plugin-api.md 5.3), so API 28 is the floor.
API=28

if [ -e build ]; then
  echo "build/ already exists; start from a clean checkout" >&2
  exit 1
fi
mkdir -p build/classes build/gen build/lib

# --- Upstream Syncthing, pinned -------------------------------------------------------------------------------------
git -c advice.detachedHead=false clone --quiet --depth 1 --branch "$SYNCTHING_TAG" https://github.com/syncthing/syncthing.git build/upstream
actual=$(git -C build/upstream rev-parse HEAD)
if [ "$actual" != "$SYNCTHING_COMMIT" ]; then
  echo "syncthing $SYNCTHING_TAG is $actual, not the pinned $SYNCTHING_COMMIT" >&2
  exit 1
fi
mkdir -p build/upstream/cmd/droidtopsyncthing
cp go/droidtopsyncthing/*.go build/upstream/cmd/droidtopsyncthing/
stamp=$(git -C build/upstream log -1 --format=%ct)
go version

# Upstream's own build sets these (build.go, ldflags); noupgrade compiles out its self-updater, since droidtop
# updates the plugin. -s -w keep each library under the installer's 64 MiB per-file cap; 16 KiB pages for Android 15.
ldflags="-s -w"
ldflags+=" -X github.com/syncthing/syncthing/lib/build.Version=$SYNCTHING_TAG"
ldflags+=" -X github.com/syncthing/syncthing/lib/build.Stamp=$stamp"
ldflags+=" -X github.com/syncthing/syncthing/lib/build.User=droidtop"
ldflags+=" -X github.com/syncthing/syncthing/lib/build.Host=droidtop-plugin-syncthing"
ldflags+=" -X github.com/syncthing/syncthing/lib/build.Tags=noupgrade,droidtop"
ldflags+=" -extldflags=-Wl,-z,max-page-size=16384"

for target in arm64-v8a:arm64:aarch64-linux-android x86_64:amd64:x86_64-linux-android; do
  IFS=: read -r abi goarch triple <<< "$target"
  out="$PWD/build/lib/$abi/libsyncthing.so"
  mkdir -p "$(dirname "$out")"
  echo "Building libsyncthing.so for $abi"
  (
    cd build/upstream
    CGO_ENABLED=1 GOOS=android GOARCH="$goarch" CC="$TOOLCHAIN/${triple}${API}-clang" \
      go build -mod=readonly -trimpath -buildmode=c-shared -tags noupgrade -ldflags "$ldflags" -o "$out" ./cmd/droidtopsyncthing
  )
  rm -f "${out%.so}.h"
done

# --- The Kotlin plugin ----------------------------------------------------------------------------------------------
cat > build/gen/SyncthingVersion.kt << EOF
package dev.droidtop.plugins.syncthing

/** Generated by build.sh from syncthing.pin. */
internal object SyncthingVersion {
    const val UPSTREAM = "$SYNCTHING_TAG"
}
EOF

kotlinc -cp "$PLUGIN_HOST_CLASSPATH:$ANDROID_JAR" -d build/classes $(find src build/gen -name '*.kt')
d8 --output build --lib "$ANDROID_JAR" $(find build/classes -name '*.class')
# classes.jar is a zip holding classes.dex at its root: what droidtop's dex loader expects.
(cd build && zip -q classes.jar classes.dex)

# --- The manifest ---------------------------------------------------------------------------------------------------
python3 - << 'PY'
import hashlib, json, os

def sha(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()

manifest = json.load(open("manifest.template.json"))
payload = [{"path": "classes.jar", "sha256": sha("build/classes.jar")}]
for abi in manifest["abis"]:
    rel = "lib/%s/libsyncthing.so" % abi
    payload.append({"path": rel, "sha256": sha(os.path.join("build", rel))})
manifest["payload"] = payload
json.dump(manifest, open("build/manifest.json", "w"), indent=2, sort_keys=True)
PY

echo "Built build/manifest.json, build/classes.jar and build/lib (unsigned)"
ls -l build/classes.jar build/lib/*/libsyncthing.so

if [ -n "${PLUGIN_SIGNING_KEY:-}" ]; then
  ./sign.sh
else
  echo "PLUGIN_SIGNING_KEY not set: stopping here, unsigned."
fi
